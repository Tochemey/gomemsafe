//go:build unix

package main

import (
	"os/exec"
	"syscall"
)

// stopGroupOnCancel runs cmd in its own process group and makes cancelling its context kill
// the whole group. Killing only the go command would leave its compile and vet children
// running and the machine busy after the benchmark stopped.
func stopGroupOnCancel(cmd *exec.Cmd) {
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	cmd.Cancel = func() error { return syscall.Kill(-cmd.Process.Pid, syscall.SIGKILL) }
}
