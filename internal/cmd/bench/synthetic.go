package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// syntheticModule is the module path of the generated corpus.
const syntheticModule = "example.com/synthetic"

// goModFile is the module file the generated corpus starts with.
const goModFile = "go.mod"

// Sizes of the generated corpus: a chain of packages, each importing the previous one, each
// with functions that exercise every part of the engine (pool calls, branches, loops, phis,
// calls through summaries).
const (
	syntheticPackages      = 40
	syntheticFuncs         = 60
	smallSyntheticPackages = 4
	smallSyntheticFuncs    = 10
)

// generateSynthetic writes the synthetic worst case into dir and returns dir.
func generateSynthetic(dir string, small bool) (string, error) {
	packages, funcs := syntheticPackages, syntheticFuncs
	if small {
		packages, funcs = smallSyntheticPackages, smallSyntheticFuncs
	}

	if err := writeFile(filepath.Join(dir, goModFile), "module "+syntheticModule+"\n\ngo 1.26\n"); err != nil {
		return "", err
	}

	for p := range packages {
		if err := writeFile(filepath.Join(dir, packageName(p), packageName(p)+".go"), syntheticPackage(p, funcs)); err != nil {
			return "", err
		}
	}

	return dir, nil
}

// syntheticPackage returns the source of package p, which imports package p-1.
func syntheticPackage(p, funcs int) string {
	var b strings.Builder

	fmt.Fprintf(&b, "// Package %s is generated by bench; do not edit.\npackage %s\n\n", packageName(p), packageName(p))
	b.WriteString("import (\n\t\"bytes\"\n\t\"sync\"\n")

	if p > 0 {
		fmt.Fprintf(&b, "\n\t%q\n", syntheticModule+"/"+packageName(p-1))
	}

	b.WriteString(")\n\n")
	b.WriteString("var pool = sync.Pool{New: func() any { return new(bytes.Buffer) }}\n\n")
	b.WriteString("// Release returns b to the pool.\nfunc Release(b *bytes.Buffer) { pool.Put(b) }\n\n")

	for f := range funcs {
		release := "Release(buf)"
		if p > 0 {
			release = packageName(p-1) + ".Release(buf)"
		}

		fmt.Fprintf(&b, `// F%[1]d exercises branches, loops, and a release through a summary.
func F%[1]d(n int, c bool) int {
	buf := pool.Get().(*bytes.Buffer)
	total := 0

	for i := range n {
		if c && i%%2 == 0 {
			buf.WriteByte('x')
		} else {
			total += buf.Len()
		}
	}

	%[2]s

	return total
}

`, f, release)
	}

	return b.String()
}

func packageName(p int) string { return fmt.Sprintf("p%d", p) }

func writeFile(path, content string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		return err
	}

	return os.WriteFile(path, []byte(content), 0o600)
}
